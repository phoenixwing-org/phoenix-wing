export const PNW_LOCALE_MESSAGES: Readonly<Record<PnwLocale, PnwLocaleMessages>> = {
  "zh-CN": PNW_ZH_CN_MESSAGES,
  "en-US": PNW_EN_US_MESSAGES,
};

export function pnwNormalizeLocale(locale: unknown): PnwLocale {
  return locale === "en-US" ? "en-US" : PNW_DEFAULT_LOCALE;
}

export function pnwTranslateLocaleMessage(
  locale: unknown,
  key: PnwLocaleMessageKey,
  values: PnwLocaleMessageValues = {},
): string {
  const template = PNW_LOCALE_MESSAGES[pnwNormalizeLocale(locale)][key];
  return template.replace(/\{([^}]+)\}/gu, (match, name: string) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  ));
}
